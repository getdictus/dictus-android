/**
 * Transcribing overlay shown while whisper.cpp processes audio.
 *
 * Reuses the same 30-bar WaveformBars as RecordingScreen, but in processing
 * mode: a traveling sine wave generated by WaveformDriver.processingEnergy().
 * This matches the iOS BrandWaveform's isProcessing mode exactly.
 *
 * The WaveformDriver advances processingPhase each frame using the same
 * formula as iOS (link.duration / 2.0), producing smooth lateral wave motion.
 *
 * Total height: LocalKeyboardSizing's total (matching RecordingScreen and KeyboardScreen, #139, #127)
 * Layout: empty top row (52.dp) + center with waveform + label + empty bottom row (46.dp)
 */
@Composable
fun TranscribingScreen(
    modifier: Modifier = Modifier,
) {
    // Dedicated driver for processing animation.
    // The driver advances processingPhase per-frame via runLoop().
    val driver = remember {
        WaveformDriver(logLabel = "keyboard").apply { isProcessing = true }
    }

    val phase by driver.processingPhase.collectAsState()
    val syntheticMotionEnabled by rememberSyntheticMotionEnabled()

    // Keep the state visible but static when Android asks to reduce motion or save power.
    LaunchedEffect(syntheticMotionEnabled) {
        if (syntheticMotionEnabled) driver.runLoop() else driver.reset()
    }

    Column(
        modifier = modifier.fillMaxWidth(),
    ) {
        // Top spacer (52.dp) — no buttons during transcription; same height as the recording's
        // top row, as iOS RecordingOverlay reserves it in every state.
        Spacer(
            modifier = Modifier
                .fillMaxWidth()
                .height(RECORDING_TOP_ROW_HEIGHT)
                .background(MaterialTheme.colorScheme.background),
        )

        // Center — animated waveform bars + label
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .height(dictationCentreHeight())
                .background(MaterialTheme.colorScheme.background),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.Center,
        ) {
            // Animated waveform bars in processing mode.
            // WaveformBars reads processingPhase and computes the sine
            // wave per-bar via WaveformDriver.processingEnergy().
            WaveformBars(
                energyLevels = emptyList(),
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 2.dp)
                    .weight(1f, fill = false)
                    .heightIn(max = 120.dp)
                    .fillMaxHeight(),
                isProcessing = true,
                processingPhase = phase,
            )

            val feedback = rememberTranscriptionFeedback(surface = "keyboard")
            val label = stringResource(dev.pivisolutions.dictus.ime.R.string.ime_transcribing)

            // "Transcription... 00:12" label
            Text(
                text = feedback?.let {
                    String.format("%s %02d:%02d", label, it.elapsedMs / 60000, (it.elapsedMs % 60000) / 1000)
                } ?: label,
                color = LocalDictusColors.current.keyText.copy(alpha = 0.6f),
                fontSize = 13.sp,
                modifier = Modifier.padding(top = 16.dp),
            )

            if (feedback?.showSlowHint == true) {
                Text(
                    text = stringResource(dev.pivisolutions.dictus.core.R.string.transcription_slow_hint),
                    color = LocalDictusColors.current.keyText.copy(alpha = 0.6f),
                    fontSize = 13.sp,
                    textAlign = TextAlign.Center,
                    maxLines = 2,
                    modifier = Modifier.padding(top = 4.dp, start = 16.dp, end = 16.dp),
                )
            }
        }

        // Bottom spacer (46.dp)
        Spacer(
            modifier = Modifier
                .fillMaxWidth()
                .height(RECORDING_BOTTOM_ROW_HEIGHT)
                .background(MaterialTheme.colorScheme.background),
        )
    }
}
